"""ISO document structure from the PDF text layer (PyMuPDF), without models.

ISO standards follow ISO/IEC Directives Part 2: numbered clauses ("4.2.4"),
annexes ("Annex A", "A.1"), captions ("Table 2 —", "Figure 1 —") and numbered
equations ("(1)" at the right margin). These rules are deterministic, so the
structure is recovered from line text, font weight and geometry:

* clause numbers must advance plausibly (figure keys "1 Datum line" and table of
  contents entries are therefore never taken for clauses);
* a clause number and its title on the same baseline are merged;
* inline symbols set as separate glyph runs ("α" + subscript "yt") are joined
  back into their text line (``merge_inline_fragments``);
* repeated page headers/footers are learned per document (``repeated_furniture``);
* tables use PyMuPDF's cell grid, filled with the cleaned text lines; bold leading
  rows are header rows; "(continued)" captions, unit notes and footnotes are kept;
* equation regions are anchored on the right-margin equation number, bounded by
  the surrounding prose, and rebuilt from glyph geometry (``parsing/formula.py``);
* "where" legends and figure keys become their own blocks.
Nothing is generated by a model; formula text that cannot be explained by the
page geometry is marked ``needs_review`` and never turned into LaTeX.
"""
